/** Polyneon is 15xx-19xx; Classic/Rayon is 10xx-14xx (and some 20xx). */
export function madeiraThreadLine(code) {
  const n = Number(code);
  if (!Number.isFinite(n)) return null;
  if (n >= 1500 && n <= 1999) return "Polyneon";
  if ((n >= 1000 && n <= 1499) || (n >= 2000 && n <= 2499)) return "Classic";
  return null;
}

